import assert from 'node:assert/strict';
import fs from 'node:fs';
const code=fs.readFileSync('functions/surveyor-save/src/main.js','utf8');
const pkg=JSON.parse(fs.readFileSync('functions/surveyor-save/package.json','utf8'));
assert.equal(pkg.version,'2.0.0');
assert.ok(Buffer.byteLength(code,'utf8') < 90000,'Save Function deve continuar pequena e dedicada');
assert.match(code,/const APP_VERSION = '2\.0\.0';/);
for(const forbidden of ['OPENROUTER','BOOTSTRAP_SECRET','/api/admin','bootstrap-admin','RENEWAL_PAYMENT','createEmailSession','JWT_SECRET']) assert.ok(!code.includes(forbidden),`Save Function nao deve conter subsistema: ${forbidden}`);
assert.match(code,/\/api\/auth\/me/,'sessao deve ser validada na API principal');
assert.match(code,/SURVEYOR_SAVE_APPWRITE_API_KEY/);
assert.match(code,/ALLOW_DYNAMIC_APPWRITE_KEY/);
assert.match(code,/MAX_SAVE_BODY_BYTES/);
assert.match(code,/MAX_PROJECT_FEATURES/);
assert.match(code,/row\.userId/,'update deve conferir owner persistido');
assert.match(code,/__surveyorSaveTransport/,'transporte funcional deve ser preservado');
assert.match(code,/path === '\/api\/projects'/);
assert.match(code,/\/api\\\/projects\\\/\(\[\^\/\]\+\)\\\/bundle/);
assert.doesNotMatch(code,/Access-Control-Allow-Credentials/,'Save Function usa credenciais omit e nao deve habilitar credentials CORS');
console.log('OK: surveyor-save 2.0.0 minimalista e com limites de confianca server-side.');
