import assert from 'node:assert/strict';
import { serializeMapFeature, restoreMapFeatures } from '../src/features/map/mapCloudPersistence.ts';
import { getVertexAppearance, updateVertexAppearance, shiftVertexAppearance, reorderVertexAppearance, copyVertexAppearanceToAll } from '../src/features/map/vertexAppearance.ts';
const original = { name: 'Gleba 1', confrontants: ['A', 'B', 'C'] };
const edited = updateVertexAppearance(original, 1, { color: '#ffffff', size: 26 });
assert.deepEqual(getVertexAppearance(edited, 1), { color: '#ffffff', size: 26 });
assert.deepEqual(getVertexAppearance(original, 1), { color: '#0c62ea', size: 14 });
assert.equal(edited.name, 'Gleba 1');
assert.deepEqual(edited.confrontants, original.confrontants);
assert.deepEqual(getVertexAppearance(updateVertexAppearance(edited, 1, { color: 'bad', size: 900 }), 1), { color: '#ffffff', size: 28 });
const inserted = shiftVertexAppearance(edited, 'insert', 0);
assert.deepEqual(getVertexAppearance(inserted, 2), { color: '#ffffff', size: 26 });
assert.deepEqual(getVertexAppearance(inserted, 1), { color: '#0c62ea', size: 14 });
const restored = shiftVertexAppearance(inserted, 'remove', 0);
assert.deepEqual(getVertexAppearance(restored, 1), { color: '#ffffff', size: 26 });
const reset = updateVertexAppearance(restored, 1, null);
assert.equal('vertexAppearance' in reset, false);
const all = copyVertexAppearanceToAll(edited, 1, 4);
for(let i=0;i<4;i++)assert.deepEqual(getVertexAppearance(all,i),{color:'#ffffff',size:26});
const flipped = reorderVertexAppearance(edited,i=>i===0?0:4-i,4);
assert.deepEqual(getVertexAppearance(flipped,3),{color:'#ffffff',size:26});
const rotated = reorderVertexAppearance(edited,i=>(i-1+4)%4,4);
assert.deepEqual(getVertexAppearance(rotated,0),{color:'#ffffff',size:26});
const feature={type:'Feature',id:'gleba-xyz',properties:edited,geometry:{type:'Polygon',coordinates:[[[-39,-13],[-39.001,-13],[-39,-12.999],[-39,-13]]]}};
const serialized=serializeMapFeature(feature);
const [restoredCloud]=restoreMapFeatures([{id:'servidor',geoJson:feature.geometry,properties:serialized}]);
assert.equal(restoredCloud.id,'gleba-xyz');
assert.deepEqual(getVertexAppearance(restoredCloud.properties,1),{color:'#ffffff',size:26});
console.log('OK: 16 verificações de aparência, reindexação e persistência GeoJSON');
