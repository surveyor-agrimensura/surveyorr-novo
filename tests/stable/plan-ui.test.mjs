import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=(p)=>fs.readFileSync(p,'utf8');
const plans=read('functions/surveyor-api/src/config/plans.js');
const block=(id)=>plans.match(new RegExp(`id: '${id}'[\\s\\S]*?permissions: \\[(.*?)\\]\\n  \\}`))?.[1]||'';
const basic=block('basic_annual'), plus=block('plus_annual'), pro=block('pro_annual');
assert.ok(basic && plus && pro,'planos anuais não encontrados');
for(const forbidden of ['layers:official','car:access','company:settings']) assert.ok(!basic.includes(forbidden),`Básico herdou permissão indevida: ${forbidden}`);
for(const required of ['layers:official','car:access']) assert.ok(plus.includes(required),`Plus sem permissão: ${required}`);
assert.ok(!plus.includes('company:settings'),'Plus não deve herdar Personalização Pro');
assert.ok(pro.includes('company:settings'),'Pro deve ter Personalização');
const auth=read('assets/js/core/auth.js'), layout=read('assets/js/core/layout.js'), portal=read('assets/js/core/portal.js'), map=read('assets/js/features/mapa/app.js'), cloud=read('assets/js/features/cloud/app.js'), nuvem=read('nuvem/index.html'), api=read('functions/surveyor-api/src/main.js');
assert.ok(api.includes("if (path === '/api/storage/status'"),'endpoint storage/status ausente');
assert.ok(auth.includes('async function loadUsageStatus()'),'frontend sem status de franquia');
assert.ok(auth.includes('async function loadStorageStatus()'),'frontend sem status de armazenamento');
assert.ok(layout.includes('svPlanUsageFooter'),'rodapé de franquias ausente');
assert.ok(portal.includes("['/consulta-car/', 'consulta-car', 'Consulta Pública CAR', 'car:access']"),'rota CAR sem gate');
assert.ok(map.includes('function canUseOfficialPropertySearch()'),'busca oficial sem gate');
assert.ok(cloud.includes('formatSize(used)') && cloud.includes('formatSize(limit)'),'projetos sem uso/total');
assert.ok(nuvem.includes('Comprar armazenamento'),'CTA armazenamento ausente');
console.log('PASS plan-ui: matriz Básico/Plus/Pro e gates principais coerentes.');
