import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const js=fs.readFileSync('assets/js/core/ui.js','utf8');
const css=fs.readFileSync('assets/css/features/mapa/app.css','utf8');
const start=js.indexOf('  function calculateMapQuickDrawerLayout(');
const end=js.indexOf('\n  function modernizeMap()',start);
assert.ok(start>=0 && end>start, 'layout geométrico deve existir em core/ui.js');
const calculate=vm.runInNewContext(js.slice(start,end)+'\ncalculateMapQuickDrawerLayout');
const desktop=calculate(476,1115,1792);
assert.equal(desktop.left,476,'a borda esquerda deve estar na divisória Camadas/Polígono');
assert.equal(desktop.width,639,'a borda direita deve terminar exatamente após Verificar');
assert.equal(desktop.columns,13,'13 colunas de 40px devem caber em 639px sem transbordamento');
const medium=calculate(350,880,1280);
assert.equal(medium.left,350);
assert.equal(medium.width,530);
assert.equal(medium.columns,11);
const mobile=calculate(220,790,390);
assert.ok(mobile.left>=8 && mobile.left+mobile.width<=390-8,'fallback deve ficar dentro da tela');
assert.equal(mobile.columns,7,'viewport estreita mantém alvos de 40px');
const edge=calculate(476,1115,1000);
assert.ok(edge.left+edge.width<=992,'quando Verificar fica fora da tela, usar limites do viewport');
assert.match(js, /drawingGroup\?\.previousElementSibling/, 'medir separador imediatamente anterior ao grupo Polígono');
assert.match(js, /verifyGroup\?\.nextElementSibling/, 'medir separador imediatamente após Verificar');
assert.match(js, /drawer\.style\.setProperty\('width',`\$\{layout\.width\}px`/, 'largura não deve ser fixa');
assert.match(js, /grid\.style\.gridTemplateColumns=`repeat\(\$\{layout\.columns\}, 40px\)`/, 'a malha deve se ajustar à largura real');
assert.match(css, /#mapQuickToolsDrawer\.map-quick-tools-drawer\.sv-map-modern-drawer\{[\s\S]*?overflow-y:auto/, 'painel deve vencer a regra antiga de overflow:hidden sem perder os controles');
console.log('PASS RC185.14: divisas exatas, 13 colunas, viewport reduzido e ajustes responsivos.');
