import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';

const renderer = readFileSync('assets/js/features/mapas/confrontantes.js', 'utf8');
const sandbox = vm.createContext({ window:{} });
vm.runInContext(renderer, sandbox);
const api=sandbox.window.SurveyorDocumentConfrontantes.create({ escape: (s)=>String(s) });
const square=[[0,0],[1,0],[1,1],[0,1],[0,0]];
const base={properties:{confrontantes:[{nome:'Vizinho',segmentIndex:0,labelColor:'#ffffff'}]}};
const override=(opts)=>api.buildConfrontanteGroups(base,square,[{id:'s1',nome:'Vizinho',startVertex:1,endVertex:2,...opts}])[0];
assert.equal(override({labelColor:'#ffffff'}).labelColor,'#111827','Branco herdado sem personalização deve virar preto');
assert.equal(override({labelColor:'#ffffff',labelColorCustomized:false}).labelColor,'#111827','Flag falso não é cor branca personalizada');
assert.equal(override({labelColor:'#ffffff',labelColorCustomized:true}).labelColor,'#ffffff','Branco escolhido explicitamente permanece');
assert.equal(override({labelColor:'#3377aa'}).labelColor,'#3377aa','Cor legada não branca é preservada');
assert.equal(override({}).labelColor,'#111827','Sem seleção deve usar preto');
assert.equal(api.buildConfrontanteGroups(base,square,[])[0].labelColor,'#111827','Confrontante novo de cadastro não pode herdar branco sem escolha');
assert.equal(api.buildConfrontanteGroups({properties:{confrontantes:[{nome:'Vizinho',segmentIndex:0,labelColor:'#ffffff',labelColorCustomized:true}]}},square,[])[0].labelColor,'#ffffff','Cor branca explicitamente registrada no cadastro permanece');
const editor=readFileSync('assets/js/core/technical-document-editor.js','utf8');
const start=editor.indexOf('  function segmentFontColor(');
const end=editor.indexOf('  function applyConfrontanteLabelColor(',start);
assert.ok(start>=0 && end>start);
const ebox=vm.createContext({});
vm.runInContext(`function confrontanteLabelColor(c) { return /^#[0-9a-f]{6}$/i.test(c||'') ? c.toLowerCase() : '#111827'; }\n${editor.slice(start,end)}\nglobalThis.resolve=segmentFontColor;`,ebox);
assert.equal(ebox.resolve({labelColor:'#ffffff'}),'#111827','Editor corrige branco legado sem flag');
assert.equal(ebox.resolve({labelColor:'#ffffff',labelColorCustomized:false}),'#111827','Editor corrige branco herdado com flag false');
assert.equal(ebox.resolve({labelColor:'#ffffff',labelColorCustomized:true}),'#ffffff','Branco personalizado respeitado no editor');
assert.equal(ebox.resolve({labelColor:'#6688cc'}),'#6688cc','Cores legadas preservadas no editor');
assert.match(renderer, /data-label-color-customized/, 'A renderização transmite a escolha individual para o editor');
console.log('PASS confrontante-default-black: preto padrão e cores personalizadas preservadas.');
