import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=(p)=>fs.readFileSync(p,'utf8');
const mapasHtml=read('mapas/index.html');
assert.ok(mapasHtml.indexOf('/assets/js/features/mapas/dimensions.js') < mapasHtml.indexOf('/assets/js/features/mapas/app.js'),'dimensions.js deve carregar antes de mapas/app.js');
const mapas=read('assets/js/features/mapas/app.js');
assert.ok(mapas.includes("return '';\n  }"),'fallback de recurso externo deve encerrar sem URL remota quebrada');
assert.ok(!mapas.includes('backgroundData: backgroundData || rawBackgroundUrl'),'croqui não pode reinjetar URL Esri que já falhou');
assert.ok(!mapas.includes("const bgHref = escape(backgroundData || rawBackgroundUrl);"),'SVG não pode depender de URL externa após falha de incorporação');
const ods=read('assets/js/features/ods/app.js');
assert.ok(ods.includes('sameCoord(coords[0], coords.at(-1))'),'ODS deve remover fechamento com tolerância de ponto flutuante');
const cloud=read('assets/js/features/cloud/app.js');
assert.ok(cloud.includes("$('projectsCount').textContent = String(filtered.length)"),'contador de projetos deve acompanhar filtro');
const loginHtml=read('login/index.html');
const loginJs=read('assets/js/core/login.js');
assert.ok(loginHtml.includes('id="toggleLoginPassword"'),'login deve oferecer mostrar/ocultar senha');
assert.ok(loginJs.includes("password.type = reveal ? 'text' : 'password'"),'toggle de senha deve funcionar');
const reurb=read('assets/js/features/loteamentos-reurb/app.js');
assert.ok(reurb.includes("['lotProjectName','Informe o nome do projeto.']"),'REURB deve validar nome do projeto');
assert.ok(reurb.includes("['lotOwner','Informe o proprietário.']"),'REURB deve validar proprietário');
assert.ok(reurb.includes("['lotCity','Informe o município.']"),'REURB deve validar município');
