'use strict';
const fs=require('node:fs'),vm=require('node:vm'),ts=require('typescript'),assert=require('node:assert/strict');
function load(file,deps={}){
 const js=ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
 const module={exports:{}};vm.runInNewContext(js,{module,exports:module.exports,require:id=>{if(Object.hasOwn(deps,id))return deps[id];throw Error(`${file}: missing ${id}`)},console,Number,Array,Object,Math,Set,Map,String,JSON,Date,RegExp,structuredClone});return module.exports;
}
