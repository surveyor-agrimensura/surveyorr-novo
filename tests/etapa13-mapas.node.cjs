const collection={type:'FeatureCollection',features:[{type:'Feature',geometry:poly},{type:'Feature',geometry:multi}]};
assert.equal(geo.projectPolygonGeometries(poly).length,1);
assert.equal(geo.projectPolygonGeometries({type:'Feature',geometry:multi}).length,1);
assert.equal(geo.projectPolygonGeometries(collection).length,2);
assert.equal(geo.projectPolygonGeometries(JSON.stringify(collection)).length,2);
assert.equal(geo.projectPolygonGeometries({type:'GeometryCollection',geometries:[poly,multi]}).length,2);
assert.equal(geo.projectPolygonGeometries('broken-json').length,0);
